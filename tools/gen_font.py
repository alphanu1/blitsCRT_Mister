def glyph_bytes(rows):
    out = []
    for r in rows:
        b = 0
        for i, c in enumerate(r):          # i = 0..4
            if c != ' ':
                b |= 1 << (6 - i)          # bit6..bit2, MSB = leftmost
        out.append(b)
    out.append(0)                          # row 7 always blank
    return out


def main():
    blank = glyph_bytes(G[' '])
    table = [blank[:] for _ in range(128)]
    for ch, rows in G.items():
        table[ord(ch)] = glyph_bytes(rows)
    # fold lowercase onto uppercase so mixed-case strings still render
    for c in range(ord('a'), ord('z') + 1):
        table[c] = table[c - 32][:]

    path = sys.argv[1] if len(sys.argv) > 1 else 'font8x8.hex'
    with open(path, 'w') as f:
        f.write("// 8x8 font ROM, 128 glyphs x 8 rows, MSB = leftmost pixel\n")
        f.write("// generated by tools/gen_font.py -- do not edit\n")
        for code in range(128):
            name = chr(code) if 32 <= code < 127 else '.'
            f.write("// 0x%02X '%s'\n" % (code, name))
            for b in table[code]:
                f.write("%02X\n" % b)

    covered = sum(1 for c in range(128) if table[c] != blank)
    print("wrote %s: 128 glyphs, %d non-blank, %d bytes"
          % (path, covered, 128 * 8))


if __name__ == '__main__':
    main()
